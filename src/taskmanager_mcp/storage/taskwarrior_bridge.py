"""Hermetic Taskwarrior CLI bridge and subprocess manager for TaskManager MCP.

Manages isolated taskrc, data directory, UDAs, locking, and translation to immutable UUIDv4.
"""

import asyncio
import fcntl
import json
import os
import time
from pathlib import Path
from typing import Any

from taskmanager_mcp.errors import ResourceNotFoundError, StorageLockTimeoutError
from taskmanager_mcp.utils.logger import get_logger

logger = get_logger("taskwarrior_bridge")


class TaskwarriorBridge:
    """Asynchronous wrapper for Taskwarrior with project isolation and file locking."""

    def __init__(self, project_dir: Path, lock_timeout_seconds: float = 5.0):
        self.project_dir = project_dir.resolve()
        self.taskwarrior_dir = self.project_dir / "taskwarrior"
        self.data_dir = self.taskwarrior_dir / "data"
        self.taskrc_path = self.taskwarrior_dir / "taskrc"
        self.locks_dir = self.project_dir / "locks"
        self.lock_path = self.locks_dir / "session.lock"
        self.lock_timeout_seconds = lock_timeout_seconds

        self._async_lock = asyncio.Lock()
        self._initialize_environment()

    def _initialize_environment(self) -> None:
        """Initializes the directory structure and hermetic taskrc if not present."""
        self.data_dir.mkdir(parents=True, exist_ok=True)
        self.locks_dir.mkdir(parents=True, exist_ok=True)
        if not self.lock_path.exists():
            self.lock_path.touch(mode=0o600)

        if not self.taskrc_path.exists():
            taskrc_content = f"""# Auto-generated by TaskManager MCP Server.
data.location={self.data_dir}
locking=1
verbose=nothing
confirmation=no
hooks=off

# User-Defined Attributes (UDAs) for Autonomous Agent Semantics
uda.component.type=string
uda.component.label=Component

uda.confidence.type=numeric
uda.confidence.label=Confidence

uda.estimate_minutes.type=numeric
uda.estimate_minutes.label=EstimateMinutes

uda.owner.type=string
uda.owner.label=OwnerAgent

uda.session_id.type=string
uda.session_id.label=SessionID

uda.evidence.type=string
uda.evidence.label=CompletionEvidence
"""
            self.taskrc_path.write_text(taskrc_content)
            logger.info("initialized_taskwarrior_sandbox", path=str(self.taskwarrior_dir))

    async def _execute_task_cli(self, *args: str) -> str:
        """Executes a Taskwarrior command under process and file locks."""
        async with self._async_lock:
            # Acquire file lock with timeout
            start_time = time.monotonic()
            lock_fd = os.open(self.lock_path, os.O_RDWR | os.O_CREAT, 0o600)
            acquired = False
            try:
                while True:
                    try:
                        fcntl.flock(lock_fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
                        acquired = True
                        break
                    except (BlockingIOError, OSError):
                        if time.monotonic() - start_time > self.lock_timeout_seconds:
                            raise StorageLockTimeoutError(
                                resource=str(self.lock_path),
                                timeout_seconds=self.lock_timeout_seconds,
                            ) from None
                        await asyncio.sleep(0.05)

                env = os.environ.copy()
                env["TASKRC"] = str(self.taskrc_path)
                cmd = ["task", f"rc:{self.taskrc_path}", *args]

                proc = await asyncio.create_subprocess_exec(
                    *cmd,
                    stdout=asyncio.subprocess.PIPE,
                    stderr=asyncio.subprocess.PIPE,
                    env=env,
                )
                stdout, stderr = await proc.communicate()

                if proc.returncode != 0 and proc.returncode != 1:
                    # Taskwarrior returns code 1 if queries match 0 tasks, which is normal for empty exports
                    stderr_msg = stderr.decode().strip()
                    logger.error(
                        "task_cli_error", cmd=cmd, returncode=proc.returncode, stderr=stderr_msg
                    )

                return stdout.decode()
            finally:
                if acquired:
                    fcntl.flock(lock_fd, fcntl.LOCK_UN)
                os.close(lock_fd)

    def _normalize_task_dict(self, raw: dict[str, Any]) -> dict[str, Any]:
        """Normalizes Taskwarrior raw dictionary fields into a consistent structure."""
        normalized = dict(raw)
        # Normalize dependencies into a clean list of UUIDs
        depends = normalized.get("depends")
        if depends is None:
            normalized["depends"] = []
        elif isinstance(depends, str):
            normalized["depends"] = [d.strip() for d in depends.split(",") if d.strip()]
        elif isinstance(depends, list):
            normalized["depends"] = [str(d).strip() for d in depends if str(d).strip()]

        # Ensure tags is a list
        if "tags" not in normalized or normalized["tags"] is None:
            normalized["tags"] = []

        return normalized

    async def list_tasks(
        self,
        status: str | None = None,
        component: str | None = None,
        tags: list[str] | None = None,
    ) -> list[dict[str, Any]]:
        """Lists tasks matching the provided criteria."""
        args = ["export"]
        if status:
            args.append(f"status:{status}")
        if component:
            args.append(f"component:{component}")
        if tags:
            for tag in tags:
                args.append(f"+{tag}")

        output = await self._execute_task_cli(*args)
        output = output.strip()
        if not output or output == "[]":
            return []

        try:
            tasks = json.loads(output)
            return [self._normalize_task_dict(t) for t in tasks]
        except json.JSONDecodeError as err:
            logger.error("task_export_json_decode_failed", raw_output=output, error=str(err))
            return []

    async def get_task(self, uuid: str) -> dict[str, Any] | None:
        """Retrieves a single task by its immutable UUIDv4."""
        output = await self._execute_task_cli(uuid, "export")
        output = output.strip()
        if not output or output == "[]":
            return None

        try:
            tasks = json.loads(output)
            if not tasks:
                return None
            return self._normalize_task_dict(tasks[0])
        except json.JSONDecodeError:
            return None

    async def add_task(
        self,
        title: str,
        component: str,
        priority: str = "M",
        tags: list[str] | None = None,
        estimate_minutes: int | None = None,
        confidence: float = 1.0,
        owner: str | None = None,
        dependencies: list[str] | None = None,
    ) -> dict[str, Any]:
        """Creates a new task in Taskwarrior and returns its normalized representation."""
        cmd_args = [
            "add",
            title,
            f"component:{component}",
            f"priority:{priority}",
            f"confidence:{confidence}",
        ]
        if estimate_minutes is not None:
            cmd_args.append(f"estimate_minutes:{estimate_minutes}")
        if owner:
            cmd_args.append(f"owner:{owner}")
        if tags:
            for tag in tags:
                cmd_args.append(f"+{tag}")
        if dependencies:
            cmd_args.append(f"depends:{','.join(dependencies)}")

        await self._execute_task_cli(*cmd_args)

        # Retrieve the newly created task (most recently created pending task with this title)
        all_tasks = await self.list_tasks(status="pending", component=component)
        for t in reversed(all_tasks):
            if t.get("description") == title:
                return t

        # Fallback: export all tasks and take the last created
        all_tasks = await self.list_tasks()
        return all_tasks[-1]

    async def modify_task(self, uuid: str, **modifications: Any) -> dict[str, Any]:
        """Modifies attributes of an existing task."""
        task = await self.get_task(uuid)
        if not task:
            raise ResourceNotFoundError(resource_type="Task", resource_id=uuid)

        cmd_args = [uuid, "modify"]
        for key, val in modifications.items():
            if val is not None:
                if isinstance(val, (int, float)):
                    cmd_args.append(f"{key}:{val}")
                else:
                    cmd_args.append(f'{key}:"{val}"')

        await self._execute_task_cli(*cmd_args)
        updated = await self.get_task(uuid)
        if not updated:
            raise ResourceNotFoundError(resource_type="Task", resource_id=uuid)
        return updated

    async def annotate_task(self, uuid: str, text: str) -> dict[str, Any]:
        """Attaches an annotation note to the task."""
        task = await self.get_task(uuid)
        if not task:
            raise ResourceNotFoundError(resource_type="Task", resource_id=uuid)

        await self._execute_task_cli(uuid, "annotate", text)
        updated = await self.get_task(uuid)
        if not updated:
            raise ResourceNotFoundError(resource_type="Task", resource_id=uuid)
        return updated

    async def complete_task(self, uuid: str) -> dict[str, Any]:
        """Marks a task as completed in Taskwarrior."""
        task = await self.get_task(uuid)
        if not task:
            raise ResourceNotFoundError(resource_type="Task", resource_id=uuid)

        await self._execute_task_cli(uuid, "done")
        completed = await self.get_task(uuid)
        if not completed:
            # If get_task fails because export excludes completed by default, query completed explicitly
            tasks = await self.list_tasks(status="completed")
            for t in tasks:
                if t.get("uuid") == uuid:
                    return t
            raise ResourceNotFoundError(resource_type="Task", resource_id=uuid)
        return completed

    async def delete_task(self, uuid: str) -> bool:
        """Deletes a task from Taskwarrior."""
        task = await self.get_task(uuid)
        if not task:
            raise ResourceNotFoundError(resource_type="Task", resource_id=uuid)

        await self._execute_task_cli(uuid, "delete", "rc.confirmation=no")
        return True

    async def add_dependency(self, task_uuid: str, depends_on_uuid: str) -> dict[str, Any]:
        """Adds depends_on_uuid to task_uuid's dependencies."""
        task = await self.get_task(task_uuid)
        if not task:
            raise ResourceNotFoundError(resource_type="Task", resource_id=task_uuid)

        current_deps = set(task.get("depends", []))
        current_deps.add(depends_on_uuid)
        deps_str = ",".join(current_deps)

        await self._execute_task_cli(task_uuid, "modify", f"depends:{deps_str}")
        updated = await self.get_task(task_uuid)
        if not updated:
            raise ResourceNotFoundError(resource_type="Task", resource_id=task_uuid)
        return updated

    async def remove_dependency(self, task_uuid: str, depends_on_uuid: str) -> dict[str, Any]:
        """Removes depends_on_uuid from task_uuid's dependencies."""
        task = await self.get_task(task_uuid)
        if not task:
            raise ResourceNotFoundError(resource_type="Task", resource_id=task_uuid)

        current_deps = set(task.get("depends", []))
        current_deps.discard(depends_on_uuid)
        deps_str = ",".join(current_deps)

        if deps_str:
            await self._execute_task_cli(task_uuid, "modify", f"depends:{deps_str}")
        else:
            await self._execute_task_cli(task_uuid, "modify", "depends:")

        updated = await self.get_task(task_uuid)
        if not updated:
            raise ResourceNotFoundError(resource_type="Task", resource_id=task_uuid)
        return updated
